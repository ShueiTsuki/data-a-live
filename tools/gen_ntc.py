"""gen_ntc.py RODATA_DUMP OUT_H: the 168-entry {R, T} NTC table at .rodata 0 of Android's qcom-vadc-common.ko
(D:\\DeepSeekHarness\\thermadc\\android) as wsl/pandora_ntc_table.h."""
import struct
import sys

data = bytearray()
for line in open(sys.argv[1], encoding='utf-8', errors='replace'):
    parts = line.split()
    if len(parts) < 2:
        continue
    try:
        int(parts[0], 16)
    except ValueError:
        continue
    for word in parts[1:5]:
        if word and len(word) % 2 == 0 and all(c in '0123456789abcdef' for c in word):
            data += bytes.fromhex(word)
        else:
            break
rows = [struct.unpack_from('<Ii', data, 8 * i) for i in range(168)]
assert all(rows[i][0] > rows[i + 1][0] for i in range(167)), 'R not decreasing'
assert all(rows[i][1] == (i - 40) * 1024 for i in range(168)), 'T not -40..127 in 1/1024 degree'
with open(sys.argv[2], 'w', newline='\n') as f:
    f.write('/*\n * NTC table of qcom_vadc7_scale_hw_calib_therm (Android qcom-vadc-common.ko .rodata 0, the same\n'
            ' * values as Linux qcom-vadc-common.c adcmap7_100k): thermistor resistance in ohm for -40 to 127\n'
            ' * degrees, one entry per degree; the temperatures are (index - 40) * 1024. Generated by\n'
            ' * tools/gen_ntc.py from `llvm-objdump -s -j .rodata qcom-vadc-common.ko`.\n */\n')
    f.write('static const uint32_t pt_ntc_ohm[168] = {\n')
    for i in range(0, 168, 8):
        f.write('\t' + ', '.join('%u' % r for r, _ in rows[i:i + 8]) + ',\n')
    f.write('};\n')
print(rows[0], rows[75], rows[167])
