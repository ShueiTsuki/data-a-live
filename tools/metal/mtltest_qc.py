# mtltest_qc.py bbNN-replay.txt DRAW[,DRAW...] > mtltest_qc.h
# From the plugin's replay capture (device/logs/bbNN-replay.txt, reassembled), the state of QuartzCore draws as C data
# for mtltest part 9, which replays them on the phone with QuartzCore's own library: the pipeline's functions and
# constants (as the plugin's text, name:type:hex), each buffer binding's bytes at commit, the vertex buffer's first four
# vertices and the draw's indices. Values only: no Apple code.
import re
import sys

sections, cur = {}, None
for line in open(sys.argv[1], encoding='utf-8'):
    if line.startswith('== draw '):
        cur = line.split()[2]
        sections[cur] = {}
    elif cur and ' = ' in line:
        k, _, v = line.rstrip('\n').partition(' = ')
        sections[cur][k] = v


def hexbytes(v, most):
    words = v.split(': ', 1)[1].split() if ': ' in v else v.split()[1:]
    data = bytes.fromhex(''.join(w for w in words if re.fullmatch(r'[0-9a-f]+', w)))
    return data[:most]


def carray(name, data):
    body = ', '.join('0x%02x' % b for b in data)
    return 'static const uint8_t %s[%d] = { %s };' % (name, max(len(data), 1), body or '0')


print('/* Generated by tools/metal/mtltest_qc.py from %s; do not edit. */' % sys.argv[1].replace('\\', '/').split('/')[-1])
print('struct QcBinding { int stage, index; const uint8_t *bytes; unsigned length; };')
print('struct QcDraw { const char *label, *vertex, *fragment, *vconst, *fconst; const struct QcBinding *bindings; unsigned count; '
      'const uint8_t *vertices; unsigned vertexBytes; };')
draws = sys.argv[2].split(',')
for d in draws:
    s = sections[d]
    pipe = s['pipe']
    m = re.match(r'v (\S+) \{([^}]*)\} f (\S+) \{([^}]*)\}', pipe)
    vfn, vconst, ffn, fconst = m.groups()
    bindings = []
    for k, v in s.items():
        m = re.match(r'commit ([vf])buffer(\d+)\+(\d+)$', k)
        if m:
            name = 'qc%s_%s%s' % (d, m.group(1), m.group(2))
            data = hexbytes(v, 1024)
            print(carray(name, data))
            bindings.append((1 if m.group(1) == 'v' else 2, int(m.group(2)), name, len(data)))
    vname = 'qc%s_vertices' % d
    vb = next((v for k, v in s.items() if re.match(r'commit vbuffer1\+', k)), None)
    print(carray(vname, hexbytes(vb, 192) if vb else b''))
    print('static const struct QcBinding qc%s_bindings[] = { %s };' % (d, ', '.join(
        '{ %d, %d, %s, %d }' % b for b in bindings)))
    print('static const struct QcDraw qc%s = { "%s", "%s", "%s", "%s", "%s", qc%s_bindings, %d, %s, %d };' % (
        d, d, vfn, ffn, vconst, fconst, d, len(bindings), vname, 192 if vb else 0))
